// Original study scenarios, written for SAA-C03. These are not AWS exam questions.
// Source links are provided for checking the underlying service behavior.
function q(id, domain, topic, difficulty, stem, options, answers, explanation, optionExplanations, takeaway, source) {
  // Stable rotation avoids teaching an answer-position pattern while keeping saved answers reproducible.
  const offset = (id * 7) % options.length;
  const rotate = values => values.slice(offset).concat(values.slice(0, offset));
  return {
    id: `perf-${String(id).padStart(3, '0')}`, domain, topic, difficulty, stem,
    options: rotate(options),
    answers: answers.map(index => (index - offset + options.length) % options.length).sort((a, b) => a - b),
    explanation, optionExplanations: rotate(optionExplanations), takeaway, source,
  };
}

